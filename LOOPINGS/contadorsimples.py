def main():
    # Definição das variáveis
    limite = 12
    contador = 1

    # Estrutura de repetição conforme o fluxograma
    while contador < limite:
        print(contador)  # imprime a informacao na tela
        contador += 1  # adiciona 1 ao contador

# Fim do programa
if __name__ == "__main__":
    main()